import * as fs from "node:fs/promises";
import * as path from "node:path";
import {
  hasExtraBlock,
  removeExtraBlockFromAgentsMd,
  renderRuleForAgentsMd,
  writeExtraBlockInAgentsMd,
  type ExtraBlockMarkers,
} from "./agentsMd";
import { type TestCommand } from "./rulesOperations";
import { assertContainedPath } from "./safePaths";

/**
 * Token-efficient subagent mode: an opt-in set of orchestration rules that
 * keep the session model for judgment and push searching, editing, and check
 * runs onto subagents running cheaper models. Off until the enable command
 * runs.
 *
 * The mode is one block in `AGENTS.md`, outside the rule pack block, and
 * nothing else: no per-tool agent files or settings. The text names model
 * tiers rather than vendor models and carries each delegate's contract, so
 * the orchestrating model applies it with whatever its tool offers.
 */

export const SUBAGENT_MODE_MARKERS: ExtraBlockMarkers = {
  start: "<!-- ai-rulebook:subagent-mode:start -->",
  end: "<!-- ai-rulebook:subagent-mode:end -->",
  label: "ai-rulebook:subagent-mode",
};

const SECTION_TEMPLATE = "section.md";
const BLOCK_NOTE =
  "<!-- Managed by the AI Rulebook extension: token-efficient subagent mode. Regenerated by the enable command; run the disable command to remove it. -->";

/** Whether the mode's block is in `AGENTS.md`. Throws on damaged markers. */
export async function isSubagentModeEnabled(workspaceRoot: string): Promise<boolean> {
  return hasExtraBlock(workspaceRoot, SUBAGENT_MODE_MARKERS);
}

/** Writes or refreshes the mode's block. The section is rendered before anything is written. */
export async function enableSubagentMode(
  workspaceRoot: string,
  bundleDir: string,
  testCommand: TestCommand
): Promise<{ created: boolean }> {
  const abs = path.join(bundleDir, SECTION_TEMPLATE);
  assertContainedPath(bundleDir, abs, "bundled subagent mode");
  let template: string;
  try {
    template = await fs.readFile(abs, "utf8");
  } catch (e) {
    const reason = e instanceof Error ? e.message : String(e);
    throw new Error(`Failed to read bundled subagent mode file ${SECTION_TEMPLATE}: ${reason}`, {
      cause: e,
    });
  }
  const section = renderRuleForAgentsMd(template, testCommand);
  const leftover = /\{\{[^}]*\}\}/.exec(section);
  if (leftover) {
    throw new Error(
      `Bundled subagent mode file ${SECTION_TEMPLATE} has an unknown placeholder ${leftover[0]}.`
    );
  }
  return writeExtraBlockInAgentsMd(workspaceRoot, SUBAGENT_MODE_MARKERS, `${BLOCK_NOTE}\n\n${section}`);
}

/** Removes the mode's block; `AGENTS.md` is deleted under the rule pack's removal rules. */
export async function disableSubagentMode(
  workspaceRoot: string
): Promise<{ removed: boolean; deletedFile: boolean }> {
  return removeExtraBlockFromAgentsMd(workspaceRoot, SUBAGENT_MODE_MARKERS);
}
